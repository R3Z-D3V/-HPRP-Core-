local activeBlips = {
    market = {},
    clothes = {},
    garage = {},
    barber = {},
    tatto = {},
}

function toggleBlips(category)
    if #activeBlips[category] > 0 then
        for _, blip in ipairs(activeBlips[category]) do
            RemoveBlip(blip)
        end
        activeBlips[category] = {}
        QBCore.Functions.Notify(string.format("%s blip'leri kapatıldı.", category), "success")
    else
        for _, blipInfo in ipairs(blips[category]) do
            local blip = AddBlipForCoord(blipInfo.pos.x, blipInfo.pos.y, blipInfo.pos.z)
            SetBlipSprite(blip, blipInfo.type)
            SetBlipDisplay(blip, 4)
            SetBlipScale(blip, blipInfo.size)
            SetBlipColour(blip, blipInfo.color)
            SetBlipAsShortRange(blip, true)
            BeginTextCommandSetBlipName("STRING")
            AddTextComponentString(blipInfo.label)
            EndTextCommandSetBlipName(blip)
            table.insert(activeBlips[category], blip)
        end
        QBCore.Functions.Notify(string.format("%s blip'leri açıldı.", category), "success")
    end
end

RegisterCommand("showblipmark", function()
    toggleBlips("market")
end)

RegisterCommand("showblipclothes", function()
    toggleBlips("clothes")
end)

RegisterCommand("showblipbarber", function()
    toggleBlips("barber")
end)

RegisterCommand("showbliptatto", function()
    toggleBlips("tatto")
end)
